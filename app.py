@app.get("/api/me")
def me():
    user = current_user()
    if not user:
        response, status = json_error("Not signed in.", 401)
        if request.cookies.get(COOKIE_NAME):
            clear_session(response)
        return response, status
    return jsonify({"username": user["username"]})


@app.get("/api/registration-status")
def registration_status():
    with connect_db() as connection:
        count = execute(connection, "SELECT COUNT(*) AS count FROM users").fetchone()["count"]
    return jsonify({"registered": count, "limit": MAX_USERS, "available": count < MAX_USERS})


@app.post("/api/register")
def register():
    if not require_same_origin():
        return json_error("Request origin was rejected.", 403)
    payload = request_json()
    if payload is None:
        return json_error("Expected a JSON request.", 400)
    username = payload.get("username")
    password = payload.get("password")
    if not isinstance(username, str) or not USERNAME_PATTERN.fullmatch(username):
        return json_error("Username must be 3–32 letters, numbers, or . _ @ - characters.", 400)
    password_error = validate_password(password)
    if password_error:
        return json_error(password_error, 400)

    rate_key = attempt_key("register")
    if is_rate_limited(rate_key, limit=10, window=60 * 60):
        return json_error("Too many account requests. Try again later.", 429)

    salt = secrets.token_bytes(16)
    digest = password_digest(password, salt)
    try:
        with connect_db() as connection:
            if DATABASE_URL:
                execute(connection, "SELECT pg_advisory_xact_lock(?)", (875021146,))
            else:
                execute(connection, "BEGIN IMMEDIATE")
            count = execute(connection, "SELECT COUNT(*) AS count FROM users").fetchone()["count"]
            if count >= MAX_USERS:
                return json_error("The calculator is limited to 5 accounts and is currently full.", 409)
            user = execute(
                connection,
                "INSERT INTO users (username, password_salt, password_hash, created_at) VALUES (?, ?, ?, ?) RETURNING id",
                (username.strip(), salt, digest, int(time.time())),
            ).fetchone()
            user_id = user["id"]
    except Exception as error:
        if not isinstance(error, sqlite3.IntegrityError) and getattr(error, "sqlstate", None) != "23505":
            raise
        record_attempt(rate_key)
        return json_error("Unable to create account with those details.", 409)

    record_attempt(rate_key)
    response = make_response(jsonify({"username": username.strip()}), 201)
    return create_session(response, user_id)


@app.post("/api/login")
def login():
    if not require_same_origin():
        return json_error("Request origin was rejected.", 403)
    payload = request_json()
    if payload is None:
        return json_error("Expected a JSON request.", 400)
    username = payload.get("username")
    password = payload.get("password")
    if not isinstance(username, str) or not isinstance(password, str):
        return json_error("Enter your username and password.", 400)
    if len(username) > 128 or len(password) > PASSWORD_MAX_CHARS:
        return json_error("Invalid username or password.", 401)

    rate_key = attempt_key(username)
    ip_rate_key = attempt_key("__login_ip__")
    if is_rate_limited(rate_key) or is_rate_limited(ip_rate_key, limit=20):
        return json_error("Too many sign-in attempts. Try again later.", 429)

    with connect_db() as connection:
        user = execute(
            connection,
            "SELECT id, username, password_salt, password_hash FROM users WHERE LOWER(username) = LOWER(?)",
            (username.strip(),),
        ).fetchone()

    salt = user["password_salt"] if user else bytes(16)
    expected_hash = user["password_hash"] if user else bytes(hashlib.sha256().digest_size)
    candidate = password_digest(password, salt)
    valid = user is not None and hmac.compare_digest(candidate, expected_hash)
    if not valid:
        record_attempt(rate_key)
        record_attempt(ip_rate_key)
        return json_error("Invalid username or password.", 401)

    with connect_db() as connection:
        execute(connection, "DELETE FROM auth_attempts WHERE attempt_key = ?", (rate_key,))
        execute(connection, "DELETE FROM auth_attempts WHERE attempt_key = ?", (ip_rate_key,))
    response = make_response(jsonify({"username": user["username"]}))
    return create_session(response, user["id"])


@app.post("/api/logout")
def logout():
    if not require_same_origin():
        return json_error("Request origin was rejected.", 403)
    response = make_response(jsonify({"ok": True}))
    return clear_session(response)


